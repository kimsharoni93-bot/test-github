import statistics

def נתח_נתוני_כדורגל(נתונים):
    """
    פונקציה זו מקבלת רשימת נתונים של שערים שנכבשו במשחקי כדורגל
    ומחזירה ניתוח סטטיסטי: ממוצע, חציון, ושחקן הכובש הרב ביותר (אם יש).
    הנתונים: רשימה של מילונים, כל מילון מייצג משחק:
      {'שם שחקן': str, 'שערים': int}
    """
    if not נתונים:
        return None
    
    שערים = [משחק['שערים'] for משחק in נתונים]
    ממוצע = statistics.mean(שערים) if שערים else 0
    חציון = statistics.median(שערים) if שערים else 0

    # מציאת השחקן המבקיע ביותר
    כובשים = {}
    for משחק in נתונים:
        שם = משחק['שם שחקן']
        שערים_שחקן = משחק['שערים']
        כובשים[שם] = כובשים.get(שם, 0) + שערים_שחקן

    שחקן_שיא = max(כובשים, key=כובשים.get) if כובשים else None

    return {
        'ממוצע שערים למשחק': ממוצע,
        'מדד חציוני לשערים': חציון,
        'הכובש הרב ביותר': שחקן_שיא
    }

# דוגמה לשימוש
if __name__ == "__main__":
    נתוני_משחקים = [
        {'שם שחקן': 'רון', 'שערים': 2},
        {'שם שחקן': 'יוסי', 'שערים': 1},
        {'שם שחקן': 'רון', 'שערים': 3},
        {'שם שחקן': 'דוד', 'שערים': 1}
    ]
    ניתוח = נתח_נתוני_כדורגל(נתוני_משחקים)
    print("תוצאות ניתוח נתוני כדורגל:")
    for מפתח, ערך in ניתוח.items():
        print(f"{מפתח}: {ערך}")